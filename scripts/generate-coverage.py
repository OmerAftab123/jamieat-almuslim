"""Regenerates docs/RESEARCH_COVERAGE.md from data/*.json. Run: python3 scripts/generate-coverage.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
D = root / 'data'
u = json.load(open(D / 'universities.json'))['universities']
sch = json.load(open(D / 'scholarships.json'))['scholarships']
dossiers = json.load(open(D / 'freeStudy.json'))['dossiers']
dos = {d['universityId'] for d in dossiers}
rows = []
for x in sorted(u, key=lambda x: x['qsRank']['position']):
    ver = [p for p in x['programs'] if p.get('status') == 'verified']
    adm = 'verified (partial)' if x['admissions'] else 'not researched'
    scs = [s for s in sch if s['universityId'] == x['id']]
    schs = f"{len(scs)} record(s)" if scs else ('not researched' if x['dataStatus']['scholarships'] == 'not-researched' else 'none recorded')
    d = 'yes' if x['id'] in dos else 'no'
    rows.append(f"| {x['qsRank']['display']} | {x['name']} | {x['country']} | {len(ver)} | {adm} | {schs} | {d} |")
n_prog = sum(1 for x in u if any(p.get('status') == 'verified' for p in x['programs']))
n_adm = sum(1 for x in u if x['admissions'])
md = f"""# Research coverage: top 150 QS universities

Generated by `scripts/generate-coverage.py` from `data/` (do not edit by hand). "Not researched" means no verified record exists, not that the answer is "no".

## Summary

- Universities in dataset: **{len(u)}** (QS 2027, ranks 1 to =150).
- With at least one verified undergraduate programme record: **{n_prog}**.
- With an admissions record: **{n_adm}**.
- With a free-study dossier: **{len(dos)}**.
- Scholarship records: **{len(sch)}**.

## What is still needed for each university

For each bachelor's degree family the platform offers:
1. Official programme title, mapped to the 102 catalogue degrees.
2. Official international undergraduate admission requirements: qualification, English minimum, subject prerequisites, deadlines.
3. Official scholarships by type: merit, need, institutional, national, regional, sports, external.
4. Official cost of attendance, with currency and basis.
5. Unofficial or trend data, labelled as such, with sources.

## National route for Pakistani students

- HEC need-based undergraduate aid is for public universities in Pakistan, not study abroad (secondary sources).
- HEC overseas awards found are postgraduate, except the Omani Scholarship (2 seats, closed for 2026-27; source `hec-oman-ug-2026`).
- No verified national undergraduate route to a top-150 university.

## Per-university coverage

| QS rank | University | Country | Verified programme records | Admissions | Scholarships | Free-study dossier |
|---|---|---|---|---|---|---|
""" + "\n".join(rows) + "\n"
(root / 'docs' / 'RESEARCH_COVERAGE.md').write_text(md, encoding='utf-8')
print('wrote coverage:', len(u), 'universities,', len(dos), 'dossiers,', len(sch), 'scholarships')
